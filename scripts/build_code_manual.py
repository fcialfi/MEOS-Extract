def _symbol_ranges(source: str) -> dict:
    """Line ranges of top-level functions/classes, methods and imports."""
    tree = ast.parse(source)
    ranges = {}
    imports = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            ranges[node.name] = (node.lineno, node.end_lineno)
            if isinstance(node, ast.ClassDef):
                for sub in node.body:
                    if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        ranges[f"{node.name}.{sub.name}"] = (sub.lineno, sub.end_lineno)
        elif isinstance(node, (ast.Import, ast.ImportFrom)):
            imports.append(node)
    if imports:
        ranges["@imports"] = (imports[0].lineno, imports[-1].end_lineno)
        ranges["@header"] = (1, max(1, imports[0].lineno - 1))
    return ranges


def _fmt(rng) -> str:
    a, b = rng
    return f"Line {a}" if a == b else f"Lines {a}-{b}"


def render_section(section: dict) -> str:
    path = ROOT / section["file"]
    source = path.read_text(encoding="utf-8")
    ranges = _symbol_ranges(source) if section["file"].endswith(".py") else {}

    def sub(match):
        name = match.group(1)
        if name not in ranges:
            raise KeyError(f"{section['file']}: unknown symbol '{name}' in explanation")
        rng = ranges[name]
        label = name if name.startswith("@") else name.split(".")[-1]
        return _fmt(rng) if name.startswith("@") else f"{_fmt(rng)} `{label}`"

    explanation = re.sub(r"\{([@A-Za-z_][\w.]*)\}", sub, section["explanation"])
    lines = source.splitlines()
    listing = "\n".join(f"{i:6d}\t{line}" for i, line in enumerate(lines, start=1))
    return (
        f"## {section['file']}\n\n### Code\n```{section['lang']}\n{listing}\n```\n\n"
        f"### Explanation\n{explanation}"
    )


def main() -> None:
    parts = [INTRO] + [render_section(s) for s in SECTIONS]
    OUTPUT.write_text("\n".join(parts).rstrip() + "\n", encoding="utf-8")
    print(f"Written {OUTPUT}")


if __name__ == "__main__":
    main()
